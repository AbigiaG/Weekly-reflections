import pandas as pd

# Load dataset
df = pd.read_excel("expanded_annotated_labeled_reddit_posts.xlsx")

# Define keyword lists
startup_keywords = [
    "start", "startup", "starting", "permits", "license", "licensing",
    "first steps", "new trailer", "new truck", "buying", "purchase",
    "planning", "business plan", "location", "commissary", "inspection",
    "costs", "budget", "loan"
]

operational_keywords = [
    "equipment", "generator", "power", "freezer", "fridge", "cold storage",
    "workflow", "staff", "hiring", "menu", "cooking", "holding", "prep",
    "profit", "cost control", "events", "parking", "daily operation",
    "sourcing", "ingredients", "POS", "maintenance"
]

def classify_post(text):
    text = str(text).lower()

    # Check startup keywords
    if any(word in text for word in startup_keywords):
        return "startup_help"

    # Check operational keywords
    if any(word in text for word in operational_keywords):
        return "operational_help"

    # Fallback: use sub_category if available
    if "start" in text or "permit" in text:
        return "startup_help"

    return "operational_help"  # default

# Apply classifier
df["ml_label"] = df["combined_text"].apply(classify_post)

# Save output
df.to_csv("reddit_with_ml_labels.csv", index=False)

df.head()

