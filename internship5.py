"""Automatic Keyword Extraction Using TF‑IDF"""

import pandas as pd
from sklearn.feature_extraction.text import TfidfVectorizer

# Combine text fields if needed
texts = df["combined_text"].fillna("")

# Create TF-IDF model
vectorizer = TfidfVectorizer(
    stop_words="english",
    max_features=2000,       # limit vocabulary
    ngram_range=(1, 2)       # unigrams + bigrams
)

tfidf_matrix = vectorizer.fit_transform(texts)

# Extract feature names
feature_names = vectorizer.get_feature_names_out()

# Function to get top keywords per post
def extract_keywords(row_index, top_n=10):
    row = tfidf_matrix[row_index].toarray().flatten()
    top_indices = row.argsort()[-top_n:][::-1]
    return [feature_names[i] for i in top_indices]

# Add keywords column
df["auto_keywords"] = [
    extract_keywords(i, top_n=8) for i in range(len(df))
]

# Save output
df.to_csv("reddit_with_auto_keywords.csv", index=False)

